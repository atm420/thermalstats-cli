//! Interface text. Supported locales: en, fr, es, de, pt, tr, ru, ko, ar.
//!
//! Each translation starts from English (`..Self::en()`), so a string that
//! hasn't been translated yet falls back to English instead of breaking the
//! build. Placeholders look like `{name}` and are filled with `fill`.

/// (code, native name) in the order shown in the language picker.
pub const LANGUAGES: [(&str, &str); 9] = [
    ("en", "English"),
    ("fr", "Français"),
    ("es", "Español"),
    ("de", "Deutsch"),
    ("pt", "Português"),
    ("tr", "Türkçe"),
    ("ru", "Русский"),
    ("ko", "한국어"),
    ("ar", "العربية"),
];

pub fn detect_locale(override_lang: Option<&str>) -> String {
    if let Some(lang) = override_lang {
        return normalize_locale(lang);
    }
    sys_locale::get_locale()
        .map(|l| normalize_locale(&l))
        .unwrap_or_else(|| "en".to_string())
}

fn normalize_locale(locale: &str) -> String {
    let lower = locale.to_lowercase();
    // Extract the language code (first 2 chars before any separator)
    let code = lower.split(|c: char| c == '-' || c == '_').next().unwrap_or("en");
    if LANGUAGES.iter().any(|(c, _)| *c == code) {
        code.to_string()
    } else {
        "en".to_string()
    }
}

/// Replace `{key}` placeholders: `fill(t.ends_at, &[("time", "14:32")])`.
pub fn fill(template: &str, values: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (key, value) in values {
        out = out.replace(&format!("{{{}}}", key), value);
    }
    out
}

